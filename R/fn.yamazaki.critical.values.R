# Critical values for the stationary, single-break Yamazaki extension.
.yamazaki.cv <- function(lambda, conf.level, k, modified = TRUE) {
  if (!is.numeric(lambda) || length(lambda) != 1L || !is.finite(lambda) ||
      lambda < 0.05 || lambda > 0.95) {
    stop("lambda must be one finite number between 0.05 and 0.95")
  }
  if (!is.numeric(conf.level) || length(conf.level) != 1L ||
      !is.finite(conf.level) || !conf.level %in% c(0.90, 0.95)) {
    stop("conf.level must be 0.90 or 0.95")
  }
  if (!is.numeric(k) || length(k) != 1L || !is.finite(k) ||
      k < 1L || k > 9L || k != as.integer(k)) {
    stop("k must be an integer between 1 and 9")
  }
  if (!is.logical(modified) || length(modified) != 1L || is.na(modified)) {
    stop("modified must be TRUE or FALSE")
  }
  if (!modified) {
    cv <- get.cv.KY(lambda, conf.level, k)
    return(c(EM = cv$cval_em, MEM = cv$cval_em, SUP = cv$cval_sup,
             AVG = cv$cval_avg, EXP = cv$cval_exp))
  }
  table <- .yamazaki.cv.tables[[if (conf.level == 0.90) 1L else 2L]]
  d <- abs(lambda - 0.5)
  basis <- c(1, 1 / (d + 1), d, d^2, d^3)
  exp.cv <- if (d < 0.4) {
    sum(table$EXP[1:5, k] * basis)
  } else {
    sum(table$EXP[6:9, k] * c(1, d, d^2, d^3))
  }
  c(EM = table$EM[k], MEM = table$EM[k],
    SUP = sum(table$SUP[, k] * basis),
    AVG = sum(table$AVG[, k] * basis), EXP = exp.cv)
}
